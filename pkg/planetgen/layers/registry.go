// registry is the global layer registry.
// Layers self-register via Register() in their init() functions.
var registry = make(map[string]Layer)

// Register adds a layer to the global registry.
// Panics if a layer with the same ID is already registered.
// Called from layer init() functions:
//
//	func init() {
//	    layers.Register(&CrustLayer{})
//	}
func Register(l Layer) {
	id := l.ID()
	if _, exists := registry[id]; exists {
		panic("layer already registered: " + id)
	}
	registry[id] = l
}

// Get retrieves a layer by ID.
// Returns nil if the layer is not registered.
func Get(id string) Layer {
	return registry[id]
}

// All returns all registered layers in dependency order.
// Uses topological sort based on DependsOn() relationships.
// Panics if a cycle is detected.
func All() []Layer {
	// Build adjacency list
	inDegree := make(map[string]int)
	adj := make(map[string][]string) // id -> dependents
	for id, layer := range registry {
		inDegree[id] = 0
		for _, dep := range layer.DependsOn() {
			if _, exists := registry[dep]; !exists {
				panic("unknown dependency: " + dep + " for layer " + id)
			}
			adj[dep] = append(adj[dep], id)
			inDegree[id]++
		}
	}

	// Kahn's algorithm
	var queue []string
	for id, deg := range inDegree {
		if deg == 0 {
			queue = append(queue, id)
		}
	}

	var ordered []Layer
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		ordered = append(ordered, registry[id])

		for _, dep := range adj[id] {
			inDegree[dep]--
			if inDegree[dep] == 0 {
				queue = append(queue, dep)
			}
		}
	}

	if len(ordered) != len(registry) {
		panic("cycle detected in layer dependencies")
	}

	return ordered
}

// ByCategory returns all layers in a given category, in dependency order.
func ByCategory(cat Category) []Layer {
	var result []Layer
	for _, layer := range All() {
		if layer.Category() == cat {
			result = append(result, layer)
		}
	}
	return result
}
